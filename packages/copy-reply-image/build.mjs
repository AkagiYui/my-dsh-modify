/**
 * Produce `client.js` from the plain-JavaScript sources.
 *
 * The browser loads a plugin's client half through `window.__ModuleLoader__`,
 * which evaluates one classic script and calls its factory; a separate module
 * import would need a bundler and a published package. `src/capture.js` and
 * `src/renderer.js` are self-contained ES modules (so the rasterizers stay
 * unit-testable in a browser), and `src/ui.js` is the factory body. This script
 * strips their `export` keywords and wraps everything in the loader envelope.
 *
 * Run with `node build.mjs` after editing a source.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const strip = (name) => fs.readFileSync(path.join(here, 'src', name), 'utf8')
  .replace(/^export\s+/gm, '');
const capture = strip('capture.js');
const renderer = strip('renderer.js');
const ui = fs.readFileSync(path.join(here, 'src/ui.js'), 'utf8');

const output = `/* Generated by build.mjs from src/capture.js, src/renderer.js and src/ui.js — edit those sources. */
window.__ModuleLoader__.load({
  id: '@akagiyui/copy-reply-image',
  factory(require) {
    const React = require('react');
    const h = React.createElement;

${capture}
${renderer}
${ui}
  },
});
`;

fs.writeFileSync(path.join(here, 'client.js'), output);
process.stdout.write(`client.js written (${output.length} bytes)\n`);
